@app.route("/generate_quiz", methods=["POST"])
def generate_quiz():
    data = request.json or {}
    lang = data.get("lang", "ru")
    subject = data.get("subject", "").strip()
    grade = data.get("grade", "").strip()
    topic_details = data.get("topic_details", "").strip()

    if not subject or not grade:
        return jsonify({"status": "error", "message": "Fill all fields!"}), 400

    # Берем вопросы из точечной базы по предмету
    lang_dict = HUGE_BANKS.get(lang, HUGE_BANKS["ru"])
    subj_list = lang_dict.get(subject, None)

    if not subj_list:
        # Если предмет редкий, создаем уникальный банк под этот предмет
        subj_list = [
            {"question": f"Вопрос №{i+1} по предмету {subject} ({grade} класс)", "answer": f"Ответ на вопрос {i+1}"}
            for i in range(25)
        ]

    # Перемешиваем и берем ровно 20 уникальных вопросов без повторений
    selected_questions = random.sample(subj_list, min(len(subj_list), 20))
    while len(selected_questions) < 20:
        selected_questions.append(random.choice(subj_list))

    random.shuffle(selected_questions)
    tiles = generate_tiles_with_surprises(selected_questions)
    return jsonify({"status": "success", "tiles": tiles})

def generate_tiles_with_surprises(questions):
    b1, b2 = random.randint(10, 50), random.randint(10, 50)
    p1, p2 = random.randint(10, 50), random.randint(10, 50)

    tile_types = ["normal"] * 16 + [
        f"bonus_{b1}", f"bonus_{b2}",
        f"penalty_{p1}", f"penalty_{p2}"
    ]
    random.shuffle(tile_types)

    tiles = []
    for i in range(20):
        t_type = tile_types[i]
        q_data = questions[i] if i < len(questions) else {"question": f"Вопрос №{i+1}", "answer": "Ответ"}
        tiles.append({
            "number": i + 1,
            "type": t_type,
            "question": q_data.get("question", ""),
            "answer": q_data.get("answer", "")
        })
    return tiles

